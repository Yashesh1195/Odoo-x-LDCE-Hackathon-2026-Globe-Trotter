/**
 * Returns a high-definition, real-time tourism photo URL for any given place or activity.
 * Supports specific landmark priority (e.g. Gir vs Somnath vs Shimla Ridge) and smart keyword tokenization.
 */
export function getLocationImage(placeName?: string, activityOrCategory?: string): string {
  if (!placeName && !activityOrCategory) {
    return "https://images.unsplash.com/photo-1488646953014-85cb44e25828?w=1200&auto=format&fit=crop&q=80";
  }

  // 1. Check specific Activity / Landmark name first (if supplied)
  if (activityOrCategory) {
    const rawAct = activityOrCategory.toLowerCase();
    const cleanAct = rawAct.replace(/[^a-z0-9]/g, "");

    // Direct match on activity name
    if (REALTIME_DESTINATION_PHOTOS[cleanAct]) {
      return REALTIME_DESTINATION_PHOTOS[cleanAct];
    }

    // Tokenized search on activity (e.g. "Visit Gir National Park", "Statue of Unity", "Kufri Snow")
    const actTokens = rawAct.split(/[\s,.-]+/).filter((t) => t.length > 2);
    for (const token of actTokens) {
      if (REALTIME_DESTINATION_PHOTOS[token]) {
        return REALTIME_DESTINATION_PHOTOS[token];
      }
    }

    // Substring match on activity
    const sortedKeys = Object.keys(REALTIME_DESTINATION_PHOTOS).sort((a, b) => b.length - a.length);
    for (const key of sortedKeys) {
      if (cleanAct.includes(key)) {
        return REALTIME_DESTINATION_PHOTOS[key];
      }
    }

    // Category match
    for (const [cat, url] of Object.entries(ACTIVITY_CATEGORY_PHOTOS)) {
      if (rawAct.includes(cat)) {
        return url;
      }
    }
  }

  // 2. Check Place Name
  if (placeName) {
    const rawPlace = placeName.toLowerCase();
    const cleanPlace = rawPlace.replace(/[^a-z0-9]/g, "");

    // Direct match on clean place
    if (REALTIME_DESTINATION_PHOTOS[cleanPlace]) {
      return REALTIME_DESTINATION_PHOTOS[cleanPlace];
    }

    // Tokenized search on place (e.g. "USA", "United States", "Shimla, Himachal Pradesh", "Gujarat, India")
    const placeTokens = rawPlace.split(/[\s,.-]+/).filter((t) => t.length > 1);
    for (const token of placeTokens) {
      if (REALTIME_DESTINATION_PHOTOS[token]) {
        return REALTIME_DESTINATION_PHOTOS[token];
      }
    }

    // Substring match with priority on longest keys
    const sortedKeys = Object.keys(REALTIME_DESTINATION_PHOTOS).sort((a, b) => b.length - a.length);
    for (const key of sortedKeys) {
      if (cleanPlace.includes(key)) {
        return REALTIME_DESTINATION_PHOTOS[key];
      }
    }
  }

  // 3. Fallback: Neutral world travel scenery (never India/Taj Mahal for generic queries)
  return "https://images.unsplash.com/photo-1488646953014-85cb44e25828?w=1200&auto=format&fit=crop&q=80";
}
